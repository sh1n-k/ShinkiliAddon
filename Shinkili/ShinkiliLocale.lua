function ShinkiliLocale.normalize(locale)
    if locale == "ko" or locale == "kr" or locale == "koKR" then
        return "ko"
    end
    return "en"
end

function ShinkiliLocale.get(locale, key)
    local code = ShinkiliLocale.normalize(locale)
    local pack = ShinkiliLocale.locales[code] or ShinkiliLocale.locales.en
    return pack[key] or ShinkiliLocale.locales.en[key] or key
end
